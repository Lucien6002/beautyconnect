-- Table de l'entite PrestationImage (images de prestation ajoutees depuis le
-- tableau de bord du professionnel, voir ProfessionalService.addPrestationImage).
-- L'entite existait sans migration : avec ddl-auto=validate, Hibernate
-- refusait de demarrer ("Schema validation: missing table [prestation_images]").
-- IF NOT EXISTS : sans effet sur une base ou la table a deja ete creee
-- (par exemple automatiquement par Hibernate avant l'arrivee de Flyway).
CREATE TABLE IF NOT EXISTS prestation_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestation_id BIGINT NOT NULL REFERENCES prestations(id) ON DELETE CASCADE,
    public_id VARCHAR(255) NOT NULL,
    secure_url VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_prestation_image_prestation ON prestation_images(prestation_id, display_order);
