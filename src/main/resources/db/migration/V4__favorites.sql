-- Professionnels mis en favori par un client. Un client ne peut mettre un
-- meme professionnel en favori qu'une seule fois.
CREATE TABLE IF NOT EXISTS favorites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES users(id),
    professional_id BIGINT NOT NULL REFERENCES professional_profiles(id),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT uk_favorites_client_professional UNIQUE (client_id, professional_id)
);
