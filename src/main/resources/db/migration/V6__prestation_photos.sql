CREATE TABLE prestation_photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestation_id BIGINT NOT NULL,
    photo_url VARCHAR(500) NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prestation_photo FOREIGN KEY (prestation_id) REFERENCES prestations(id) ON DELETE CASCADE
);

CREATE INDEX idx_prestation_photo_prestation ON prestation_photos(prestation_id);
CREATE INDEX idx_prestation_photo_order ON prestation_photos(prestation_id, display_order);
